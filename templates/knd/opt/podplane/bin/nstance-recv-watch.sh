set -euo pipefail

# Process nstance-agent receive output.

INSTALLED_VMCONFIG_MANIFEST="/opt/podplane/share/vmconfig-installed.json"
BOOTSTRAP_DONE="/opt/podplane/bootstrap.done"
DETECTED_ENV="/opt/podplane/etc/detected.env"
MUTABLE_ENV="/opt/podplane/etc/mutable.env"
NSTANCE_BASE="/opt/nstance-agent"
NSTANCE_RECV="${NSTANCE_BASE}/recv"
LAST_WRITE_FILES_FILE="${NSTANCE_RECV}/write-files.last"
START_TIME_FILE="/opt/nstance-recv-watch.last"

# shellcheck source=/dev/null
source /opt/podplane/lib/helpers.sh
# shellcheck source=/dev/null
source /opt/podplane/lib/features.sh

load_vmconfig_kind "$INSTALLED_VMCONFIG_MANIFEST"

declare -A ALLOWED_RECEIVED_FILES=(
  [mutable.env]=1
  [ca.crt]=1
  [ca.pub]=1
  [service-accounts.pub]=1
  [service-accounts.key]=1
  [containerd.client.crt]=1
  [front-proxy.client.crt]=1
  [kube-apiserver.client.crt]=1
  [kube-apiserver.server.crt]=1
  [kube2iam.client.crt]=1
  [kubelet.client.crt]=1
  [kubelet.server.crt]=1
  [netsy.client.crt]=1
  [netsy.server.crt]=1
  [registry.server.crt]=1
)
if [ "$VMCONFIG_KIND" = "knc" ]; then
  ALLOWED_RECEIVED_FILES[kube-controller-manager.client.crt]=1
  ALLOWED_RECEIVED_FILES[kube-scheduler.client.crt]=1
fi

# Remove the trigger file to allow systemd to queue future triggers
# while this script is running
if [ -f "${LAST_WRITE_FILES_FILE}" ]; then
  rm -f "${LAST_WRITE_FILES_FILE}"
fi

# Store the current time (in nanoseconds) in START_TIME var
START_TIME=$(date +%s%N)

# Ensure there's a 1 second gap to allow multiple subsequent write-files
# invocations to be processed with ideally one restarting of services.
# See service restarting at end of this script.
sleep 1

# Load the last completion time
LAST_START_TIME=0
if [ -f "${START_TIME_FILE}" ]; then
  LAST_START_TIME=$(cat "${START_TIME_FILE}")
fi

echo "Last Run: ${LAST_START_TIME}"
echo "Start Time: ${START_TIME}"

# Check if mutable.env has changed since the last run.
# Note that `stat` returns the last modified time in seconds, and our
# start time is in nanoseconds, so we need to convert it.
if [ -f "${NSTANCE_RECV}/mutable.env" ]; then
  LAST_MODIFIED=$(stat -c %Y "${NSTANCE_RECV}/mutable.env")999999999
  if [ "${LAST_MODIFIED}" -ge "${LAST_START_TIME}" ]; then
    if [ ! -f "$BOOTSTRAP_DONE" ]; then
      fatal "bootstrap has not completed"
    fi
    if [ -f "$BOOTSTRAP_DONE" ] && { [ ! -s "$DETECTED_ENV" ] || [ ! -s "$MUTABLE_ENV" ]; }; then
      fatal "bootstrap marker exists but required env files are missing or empty"
    fi

    echo "Updating mutable.env..."
    /opt/podplane/bin/update-mutable-env.sh \
      "${NSTANCE_RECV}/mutable.env" \
      "$MUTABLE_ENV"
  fi
fi

# Iterate over certificate and key files from nstance receive dir
for file in "${NSTANCE_RECV}"/*.{crt,pub,key}; do
  if [ ! -f "${file}" ]; then
    # skip non-files (e.g. directories, symlinks, etc.)
    continue
  fi

  DEST_FILE=$(basename "${file}")
  if [ -z "${ALLOWED_RECEIVED_FILES[$DEST_FILE]+x}" ]; then
    echo "Skipping ${DEST_FILE}: not allowed for this vmconfig kind."
    continue
  fi

  LAST_MODIFIED=$(stat -c %Y "${file}")999999999
  if [ "${LAST_MODIFIED}" -lt "${LAST_START_TIME}" ]; then
    continue
  fi

  DEST_GROUP="podplane"
  DEST_MODE="0640"
  if [[ "${file}" == *.crt ]]; then
    DEST_DIR="/opt/crt"
  elif [[ "${file}" == *.pub ]]; then
    DEST_DIR="/opt/pub"
  elif [[ "${file}" == *.key ]]; then
    # Note: for most certificates, private keys are generated by nstance-agent
    # locally under /opt/nstance-agent/keys and copied in the separate
    # loop below, not received here. This section is for keys sent by nstance-server.
    if [ "${file}" = "${NSTANCE_RECV}/service-accounts.key" ]; then
      # Special handling for the service accounts key
      DEST_DIR="/opt/key/kube-apiserver"
      DEST_GROUP="kube-apiserver"
    else
      # if it's a .key file, use the name of the file as its subdir
      DEST_SERVICE=$(echo "${DEST_FILE}" | cut -d. -f1)
      DEST_DIR="/opt/key/${DEST_SERVICE}"
      DEST_GROUP="$DEST_SERVICE"
    fi
  else
    echo "Unknown file type: ${file}"
    exit 1
  fi

  echo "Copying ${file} to ${DEST_DIR}/${DEST_FILE}..."
  install -m "$DEST_MODE" -o root -g "$DEST_GROUP" "${file}" "${DEST_DIR}/${DEST_FILE}"
done

# Most certificates which arrive through recv have their private keys generated
# locally by nstance-agent - for those, copy the generated keys into the appropriate
# location for each corresponding allowed certs that were copied above.
for file in "${NSTANCE_BASE}"/keys/*.key; do
  [ -f "$file" ] || continue

  KEY_FILE=$(basename "$file")
  CERT_FILE="${KEY_FILE%.key}.crt"
  if [ -z "${ALLOWED_RECEIVED_FILES[$CERT_FILE]+x}" ] || [ ! -f "/opt/crt/${CERT_FILE}" ]; then
    continue
  fi

  DEST_SERVICE=$(echo "$KEY_FILE" | cut -d. -f1)
  DEST_GROUP="$DEST_SERVICE"
  if [ "$DEST_SERVICE" = "registry" ]; then
    # The registry service runs as the zot user/group.
    DEST_GROUP="zot"
  elif [ "$KEY_FILE" = "front-proxy.client.key" ]; then
    # The front-proxy client cert is used by kube-apiserver for aggregated API proxying
    DEST_SERVICE="kube-apiserver"
    DEST_GROUP="kube-apiserver"
  fi
  DEST_DIR="/opt/key/${DEST_SERVICE}"

  echo "Copying ${file} to ${DEST_DIR}/${KEY_FILE}..."
  install -m 0640 -o root -g "$DEST_GROUP" "$file" "${DEST_DIR}/${KEY_FILE}"
done

# Check that a new trigger hasn't been created while we were processing
# the previous one, and if there's nothing queued, run the configure.sh
# script and then restart services.
if [ ! -f "${LAST_WRITE_FILES_FILE}" ]; then
  containerd_config_hash="$(sha256sum /etc/containerd/config.toml | awk '{print $1}')"
  echo "Running configure.sh..."
  /opt/podplane/bin/configure.sh

  # shellcheck source=/dev/null
  source /opt/podplane/etc/user-data.env
  # shellcheck source=/dev/null
  source "$DETECTED_ENV"
  # shellcheck source=/dev/null
  source "$MUTABLE_ENV"
  case "${TELEMETRY_ENABLED:-false}" in
    true|false) ;;
    *) fatal "TELEMETRY_ENABLED must be true or false" ;;
  esac
  case "${TELEMETRY_LOG_CLOUDINIT:-true}" in
    true|false) ;;
    *) fatal "TELEMETRY_LOG_CLOUDINIT must be true or false" ;;
  esac
  case "${REGISTRY_ENABLED:-true}" in
    true|false) ;;
    *) fatal "REGISTRY_ENABLED must be true or false" ;;
  esac

  echo "Restarting services directly..."
  systemctl daemon-reload
  updated_containerd_config_hash="$(sha256sum /etc/containerd/config.toml | awk '{print $1}')"
  if [ "$updated_containerd_config_hash" != "$containerd_config_hash" ]; then
    restart_service containerd
  fi
  if fluent_bit_enabled; then
    restart_service fluent-bit
  else
    systemctl disable fluent-bit || true
    systemctl stop fluent-bit || true
  fi
  if zot_enabled; then
    restart_service zot
  else
    systemctl disable zot || true
    systemctl stop zot || true
  fi
  if netsy_enabled; then
    restart_service netsy
  fi
  if kube_apiserver_enabled; then
    restart_service kube-apiserver
  fi
  if kube_controller_manager_enabled; then
    restart_service kube-controller-manager
  fi
  if kube_scheduler_enabled; then
    restart_service kube-scheduler
  fi
  restart_service kubelet
  echo "Done restarting services."
fi

# Log the start time to the last start time file
echo "${START_TIME}" > "${START_TIME_FILE}"
echo "Updated last start time. Success."
